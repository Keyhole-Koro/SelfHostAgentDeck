const child = spawn(process.execPath, [join(ROOT, "src", "cli.ts"), "view", "--port", "0", "--remote", "https://agents.example.com", "--remote-port", "0"], { cwd: repo, env });
const { url, remotePort } = await new Promise<{ url: string; remotePort: number }>((resolve, reject) => {
  let out = "";
  child.stdout!.on("data", (d: Buffer) => {
    out += String(d);
    const u = /http:\/\/127\.0\.0\.1:\d+\/#t=\w+/.exec(out);
    const r = /tunnel at http:\/\/127\.0\.0\.1:(\d+)/.exec(out);
    if (u && r) resolve({ url: u[0], remotePort: Number(r[1]) });
  });
  child.on("exit", () => reject(new Error("agent-deck view exited")));
});

