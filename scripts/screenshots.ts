/** https://agents.example.com, served by the page's remote listener as the tunnel would. */
async function asTunnel(page: Page): Promise<void> {
  await page.route("https://agents.example.com/**", async (route) => {
    const req = route.request();
    const u = new URL(req.url());
    const res = await new Promise<{ status: number; headers: Record<string, string>; body: Buffer }>((resolve, reject) => {
      const r = request({ host: "127.0.0.1", port: remotePort, method: req.method(), path: u.pathname + u.search, headers: { ...req.headers(), host: "agents.example.com" } }, (resp) => {
        const chunks: Buffer[] = [];
        resp.on("data", (c: Buffer) => chunks.push(c));
        resp.on("end", () => {
          const headers: Record<string, string> = {};
          for (const [k, v] of Object.entries(resp.headers)) if (v !== undefined) headers[k] = Array.isArray(v) ? v.join(", ") : String(v);
          resolve({ status: resp.statusCode ?? 500, headers, body: Buffer.concat(chunks) });
        });
      });
      r.on("error", reject);
      const data = req.postDataBuffer();
      if (data) r.write(data);
      r.end();
    });
    await route.fulfill(res);
  });
}

async function shot(browser: Browser, name: string, opts: BrowserContextOptions, steps: (page: Page) => Promise<void>): Promise<void> {
  const context = await browser.newContext({ colorScheme: "light", ...opts });
  const page = await context.newPage();
  await steps(page);
  await page.waitForTimeout(600);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  console.log(`docs/screenshots/${name}.png`);
  await context.close();
}

