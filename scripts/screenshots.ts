function git(cwd: string, ...args: string[]): void {
  const past = "2026-01-05T10:00:00Z";
  execFileSync("git", args, { cwd, env: { ...env, GIT_AUTHOR_DATE: past, GIT_COMMITTER_DATE: past, GIT_AUTHOR_NAME: "demo", GIT_AUTHOR_EMAIL: "demo@example.com", GIT_COMMITTER_NAME: "demo", GIT_COMMITTER_EMAIL: "demo@example.com" } });
}

function write(dir: string, rel: string, lines: string[]): void {
  mkdirSync(join(dir, rel, ".."), { recursive: true });
  writeFileSync(join(dir, rel), lines.join("\n") + "\n");
}

/** A repository with these files committed. */
function project(name: string, files: Record<string, string[]>): string {
  const dir = join(demo, name);
  mkdirSync(dir, { recursive: true });
  git(dir, "init", "-q", "-b", "main");
  for (const [rel, lines] of Object.entries(files)) write(dir, rel, lines);
  git(dir, "add", ".");
  git(dir, "commit", "-q", "-m", "Initial commit");
  return dir;
}

